function classifyPublisher(publisherRaw) {
  const publisher = (publisherRaw || '').toLowerCase()
  if (restrictedPublishers.some(p => publisher.includes(p.toLowerCase()))) return 'restricted'
  if (contractCheckPublishers.some(p => publisher.includes(p.toLowerCase()))) return 'contract-check'
  if (allowedPublishers.some(p => publisher.includes(p.toLowerCase()))) return 'allowed'
  return 'not-allowed'
}

